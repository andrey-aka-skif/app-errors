/**
 * Создаёт функцию извлечения деталей ошибки из ответа сервера.
 * @description Axios кладёт тело ответа в свойство "data", Superagent —
 * в "body". Всё остальное в разборе совпадает, поэтому отличается только ключ,
 * и оба билдера пользуются одной реализацией.
 *
 * Порядок проверок: "detail", "Detail", всё тело, null. Оператор "??" выбран
 * намеренно: null не проходит и уступает следующему варианту, поэтому тело
 * { detail: null } даёт всё тело целиком, а пустая строка проходит
 * и сохраняется как есть.
 *
 * @param {string} key - Имя свойства ответа с телом: "data" или "body"
 * @returns {(response: *) => *} Функция извлечения деталей
 */
export const createDetailExtractor = key => response =>
  response?.[key]?.detail ?? response?.[key]?.Detail ?? response?.[key] ?? null
