/**
 * Проверяет обязательный строковый параметр конструктора.
 * @description Пустое или отсутствующее значение — ошибка программиста,
 * а не состояние выполнения: без проверки объект ошибки создался бы
 * с type === undefined, и дефект всплыл бы далеко от места создания.
 *
 * Выбрасывается именно TypeError, а не LogicError: класс, бросающий из своего
 * конструктора собственный тип, путает при чтении стектрейса, а TypeError —
 * то, что платформа бросает ровно в этом случае.
 *
 * В билдерах не используется: те вызываются в catch-блоках и не имеют права
 * выбрасывать исключение.
 *
 * @param {*} value - Проверяемое значение
 * @param {string} className - Имя класса для текста сообщения
 * @param {string} parameter - Имя параметра для текста сообщения
 * @throws {TypeError} Если значение не строка или строка пуста
 */
export const assertRequiredString = (value, className, parameter) => {
  if (typeof value !== 'string' || value.trim() === '') {
    throw new TypeError(
      `${className}: параметр "${parameter}" обязателен и должен быть непустой строкой`
    )
  }
}
